// Builds public/tigertag-db.js from the public TigerTag registry (CC0-1.0):
// https://github.com/TigerTag-Project/TigerTag-RFID-Guide, folder "database".
// Only the id -> name pairs the app needs are kept, so nothing is fetched at run time.
// Usage: node scripts/make-tigertag-db.js <path to the registry's database folder>
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const source = process.argv[2];
if (!source) {
  console.error('Usage: node scripts/make-tigertag-db.js <path to the registry database folder>');
  process.exit(1);
}
const load = name => JSON.parse(readFileSync(path.join(source, `${name}.json`), 'utf8'));
const pairs = (rows, key) => Object.fromEntries(rows.map(r => [r.id, r[key]]).sort((a, b) => a[0] - b[0]));

const GRAMS = { mg: 0.001, g: 1, kg: 1000 };
const tables = {
  BRANDS: pairs(load('id_brand'), 'name'),
  MATERIALS: pairs(load('id_material'), 'label'),
  ASPECTS: pairs(load('id_aspect'), 'label'),
  // grams per unit, for the units that measure a weight
  GRAMS_PER_UNIT: Object.fromEntries(load('id_measure_unit').filter(u => u.label in GRAMS).map(u => [u.id, GRAMS[u.label]])),
};

const out = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'public', 'tigertag-db.js');
const body = Object.entries(tables).map(([name, table]) => `export const ${name} = ${JSON.stringify(table)};`).join('\n');
writeFileSync(out, `// Generated by scripts/make-tigertag-db.js on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
// Data: TigerTag public registry, CC0-1.0, https://github.com/TigerTag-Project/TigerTag-RFID-Guide
${body}
`);
console.log(`Wrote ${out}: ${Object.entries(tables).map(([n, t]) => `${Object.keys(t).length} ${n.toLowerCase()}`).join(', ')}`);
